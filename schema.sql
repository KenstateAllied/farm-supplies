CREATE TABLE mobil (
    id_mobil INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ekspedisi TEXT NOT NULL DEFAULT '',
    spe TEXT NOT NULL DEFAULT '',
    jenis TEXT NOT NULL DEFAULT '',
    nopol TEXT NOT NULL DEFAULT '',
    supir TEXT NOT NULL DEFAULT '',
    hp TEXT NOT NULL DEFAULT '',
    masuk TIMESTAMP WITHOUT TIME ZONE,
    muat TIMESTAMP WITHOUT TIME ZONE,
    keluar TIMESTAMP WITHOUT TIME ZONE,
    tujuan TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'belum muat'
);

CREATE TABLE "user" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "user" TEXT NOT NULL,
    pass TEXT NOT NULL,
    level TEXT NOT NULL DEFAULT '',
    since DATE,
    foto TEXT NOT NULL DEFAULT ''
);

CREATE TABLE setting (
    id_setting INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creator TEXT NOT NULL DEFAULT '',
    judul TEXT NOT NULL DEFAULT '',
    "desc" TEXT NOT NULL DEFAULT '',
    slider1 TEXT NOT NULL DEFAULT '',
    slider2 TEXT NOT NULL DEFAULT '',
    slider3 TEXT NOT NULL DEFAULT ''
);

INSERT INTO setting (id_setting)
VALUES (1)
ON CONFLICT (id_setting) DO NOTHING;

SELECT setval(
    pg_get_serial_sequence('setting', 'id_setting'),
    GREATEST((SELECT MAX(id_setting) FROM setting), 1)
);
